def resolve_root() -> Path:
    """$KOLIR_ROOT -> physical checkout around this script -> /usr/share/kolir."""
    override = os.environ.get("KOLIR_ROOT", "").strip()
    if override:
        return Path(override).expanduser().resolve()

    script = Path(os.path.realpath(__file__))
    candidate = script.parent.parent
    if (candidate / ROOT_MARKER).is_file():
        return candidate

    package = Path("/usr/share/kolir")
    if (package / ROOT_MARKER).is_file():
        return package.resolve()

    return candidate


def require_root() -> Path:
    root = resolve_root()
    if not (root / ROOT_MARKER).is_file():
        raise SetupError(
            f"'{root}' does not look like a kolir checkout or package "
            f"(missing {ROOT_MARKER}).\n"
            "Set KOLIR_ROOT to the repository/package root."
        )
    return root


def git_describe(root: Path) -> str | None:
    git = shutil.which("git")
    if not git:
        return None
    try:
        result = subprocess.run(
            [git, "-C", str(root), "describe", "--tags", "--always", "--dirty"],
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    value = result.stdout.strip()
    return value if result.returncode == 0 and value else None


