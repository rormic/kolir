class Deployer:
    """Applies the user glue, reporting every change and honouring --dry-run."""

    def __init__(self, root: Path, dry_run: bool = False, force: bool = False):
        self.root = root
        self.dry_run = dry_run
        self.force = force
        self.changes: list[str] = []

    # -- reporting ---------------------------------------------------------
    def _change(self, done: str, planned: str | None = None) -> None:
        self.changes.append(done)
        if self.dry_run:
            info("would " + (planned or done))
        else:
            info(done)

    def note(self, message: str) -> None:
        info(message)

    # -- primitives --------------------------------------------------------
    def backup_name(self, path: Path) -> Path:
        stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
        candidate = path.with_name(f"{path.name}.bak.{stamp}")
        counter = 1
        while os.path.lexists(candidate):
            candidate = path.with_name(f"{path.name}.bak.{stamp}.{counter}")
            counter += 1
        return candidate

    def backup(self, path: Path) -> Path:
        candidate = self.backup_name(path)
        self._change(
            f"backed up {path} -> {candidate}",
            f"back up {path} -> {candidate}",
        )
        if not self.dry_run:
            path.rename(candidate)
        return candidate

    def _write(self, path: Path, content: str) -> None:
        if self.dry_run:
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        handle_fd, tmp_name = tempfile.mkstemp(
            prefix=f".{path.name}.", dir=str(path.parent)
        )
        try:
            with os.fdopen(handle_fd, "w", encoding="utf-8") as handle:
                handle.write(content)
            os.chmod(tmp_name, 0o644)
            os.replace(tmp_name, path)
        except BaseException:
            if os.path.exists(tmp_name):
                os.unlink(tmp_name)
            raise

    def ensure_dir(self, path: Path) -> None:
        if path.is_dir():
            return
        if os.path.lexists(path) and not path.is_dir():
            raise SetupError(f"'{path}' exists and is not a directory")
        self._change(f"created directory {path}", f"create directory {path}")
        if not self.dry_run:
            path.mkdir(parents=True, exist_ok=True)

    def ensure_symlink(self, dst: Path, src: Path) -> None:
        dst = Path(dst)
        src = Path(src)
        wanted = os.path.normpath(str(src))
        if dst.is_symlink():
            current = lexical_link_target(dst)
            if current == wanted and not self.force:
                return
            self.backup(dst)
        elif os.path.lexists(dst):
            self.backup(dst)

        self._change(f"created symlink {dst} -> {src}", f"create symlink {dst} -> {src}")
        if not self.dry_run:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.symlink_to(src)

    def ensure_symlink_if_absent(self, dst: Path, src: Path) -> None:
        """Create a link when the path is missing; leave existing files alone.

        A broken symlink is treated as missing (it cannot serve its purpose).
        """
        dst = Path(dst)
        if dst.is_symlink():
            if dst.exists():
                return
            self.backup(dst)
            if self.dry_run:
                self._change(
                    f"created symlink {dst} -> {src}",
                    f"create symlink {dst} -> {src}",
                )
                return
        elif os.path.lexists(dst):
            return
        self.ensure_symlink(dst, src)

    def ensure_file(self, path: Path, content: str) -> None:
        path = Path(path)
        if path.is_symlink():
            self.backup(path)
        elif os.path.lexists(path):
            if path.is_dir():
                self.backup(path)
            else:
                try:
                    current = path.read_text(encoding="utf-8")
                except OSError:
                    current = None
                if current == content:
                    return
                self.backup(path)
        self._change(f"wrote {path}", f"write {path}")
        self._write(path, content)

    def ensure_file_if_absent(self, path: Path, content: str) -> None:
        path = Path(path)
        if path.is_symlink() and not path.exists():
            self.backup(path)
        elif os.path.lexists(path):
            return
        self._change(f"wrote {path}", f"write {path}")
        self._write(path, content)

    def copy_if_absent(self, src: Path, dst: Path, label: str) -> None:
        dst = Path(dst)
        if dst.is_symlink() and not dst.exists():
            self.backup(dst)
            if self.dry_run:
                self._change(f"copied {src} -> {dst}", f"copy {src} -> {dst}")
                return
        elif os.path.lexists(dst):
            self.note(f"{label}: kept existing {dst}")
            return
        self._change(f"copied {src} -> {dst}", f"copy {src} -> {dst}")
        if not self.dry_run:
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)

    def ensure_version(self) -> None:
        path = self.root / VERSION_FILE
        # A package install lives read-only under /usr/share/kolir and ships its
        # own .version; only a writable checkout gets refreshed here.
        if not os.access(self.root, os.W_OK):
            if path.is_file():
                self.note(f"version: kept package-provided {path}")
            else:
                self.note(
                    f"version: {self.root} is read-only and has no {VERSION_FILE}; "
                    "kolir version will fall back to unknown"
                )
            return
        content = setup_version(self.root) + "\n"
        try:
            current = path.read_text(encoding="utf-8") if path.is_file() else None
        except OSError:
            current = None
        if current == content:
            return
        self._change(f"wrote {path}", f"write {path}")
        self._write(path, content)

    # -- feature blocks ----------------------------------------------------
    def configure_matugen_templates(self, dst: Path, src: Path) -> None:
        """Link the whole directory, or fill a real local directory per file."""
        dst = Path(dst)
        if dst.is_symlink():
            self.ensure_symlink(dst, src)
            return
        if dst.is_dir():
            for template in sorted(src.iterdir()):
                if not template.is_file():
                    continue
                local = dst / template.name
                if local.is_symlink():
                    if lexical_link_target(local) == os.path.normpath(str(template)):
                        continue
                    if local.exists():
                        self.note(
                            f"matugen: kept local template link {local} "
                            f"(-> {lexical_link_target(local)})"
                        )
                        continue
                    self.backup(local)
                elif os.path.lexists(local):
                    continue
                self._change(
                    f"linked template {local} -> {template}",
                    f"link template {local} -> {template}",
                )
                if not self.dry_run:
                    local.symlink_to(template)
            return
        self.ensure_symlink(dst, src)

    def configure_obsidian(self, config_path: Path, output: str) -> None:
        output_path = Path(output)
        self.ensure_dir(output_path.parent)

        try:
            original = config_path.read_text(encoding="utf-8")
        except OSError as exc:
            raise SetupError(f"cannot read {config_path}: {exc}") from exc

        updated = replace_obsidian_block(original, output)
        if updated == original:
            if config_path.is_symlink():
                self.note(
                    f"obsidian: {config_path} already contains the entry for {output}; "
                    "the symlink was left in place"
                )
            else:
                self.note(f"obsidian: {config_path} already writes to {output}")
            return

        if config_path.is_symlink():
            # Never write through a link into a checkout: replace it with a
            # local copy so the user's edits are not lost on the next update.
            self.backup(config_path)
            self.note(
                f"obsidian: replaced the {config_path} symlink with a local copy "
                "before adding the entry"
            )
        else:
            self.backup(config_path)

        self._change(
            f"added [templates.obsidian] -> {output} to {config_path}",
            f"add [templates.obsidian] -> {output} to {config_path}",
        )
        self._write(config_path, updated)


def toml_value(value: str) -> str:
    if "'" not in value and "\\" not in value and "\n" not in value:
        return f"'{value}'"
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def replace_obsidian_block(text: str, output: str) -> str:
    """Replace (or append) exactly one [templates.obsidian] block."""
    lines = text.splitlines()
    start = None
    for index, line in enumerate(lines):
        if line.strip() == OBSIDIAN_SECTION:
            start = index
            break

    header_and_keys = [
        OBSIDIAN_SECTION,
        f"input_path = {toml_value(OBSIDIAN_INPUT)}",
        f"output_path = {toml_value(output)}",
    ]

    if start is None:
        body = text.rstrip("\n")
        if body:
            body += "\n\n"
        return body + "\n".join(header_and_keys) + "\n"

    end = len(lines)
    for index in range(start + 1, len(lines)):
        stripped = lines[index].strip()
        if stripped.startswith("[") and stripped.endswith("]"):
            end = index
            break

    extras: list[str] = []
    for line in lines[start + 1 : end]:
        stripped = line.strip()
        if stripped.startswith("input_path") or stripped.startswith("output_path"):
            continue
        extras.append(line)
    while extras and not extras[0].strip():
        extras.pop(0)
    while extras and not extras[-1].strip():
        extras.pop()

    block = header_and_keys + extras
    new_lines = lines[:start] + block
    tail = lines[end:]
    if tail:
        new_lines.append("")
        new_lines.extend(tail)
    return "\n".join(new_lines).rstrip("\n") + "\n"


