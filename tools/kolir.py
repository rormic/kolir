def graphical_session_available() -> bool:
    return bool(
        os.environ.get("WAYLAND_DISPLAY")
        or os.environ.get("HYPRLAND_INSTANCE_SIGNATURE")
    )


def hyprland_running() -> bool:
    hyprctl = shutil.which("hyprctl")
    if not hyprctl:
        return False
    try:
        result = subprocess.run(
            [hyprctl, "-j", "monitors"], capture_output=True, text=True, timeout=10
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return result.returncode == 0


def running_shell_configs(qs: str) -> list[str]:
    """Config directories of every running kolir Quickshell instance."""
    try:
        result = subprocess.run(
            [qs, "list", "--all"], capture_output=True, text=True, timeout=10
        )
    except (OSError, subprocess.SubprocessError):
        return []
    configs: list[str] = []
    for line in (result.stdout or "").splitlines():
        marker = "Config path:"
        if marker not in line:
            continue
        path = line.split(marker, 1)[1].strip()
        if not path.endswith("/config/quickshell/shell.qml"):
            continue
        directory = os.path.dirname(os.path.dirname(path))
        if directory and directory not in configs:
            configs.append(directory)
    return configs


def kill_other_shells(qs: str, config: Path) -> None:
    """Stop every kolir shell, including one left behind by another root.

    Before the package existed the shell ran from a checkout; after `kolir
    setup` moves the links to /usr/share/kolir a reload has to stop that old
    instance too, otherwise two bars (and two notification servers) run.
    """
    targets = [str(config)]
    for directory in running_shell_configs(qs):
        if directory not in targets:
            targets.append(directory)

    for directory in targets:
        killed = False
        try:
            result = subprocess.run(
                [qs, "-p", directory, "kill"],
                capture_output=True,
                text=True,
                timeout=10,
            )
            killed = result.returncode == 0
        except (OSError, subprocess.SubprocessError):
            killed = False
        if not killed:
            for pattern in (f"qs -p {directory}", f"quickshell -p {directory}"):
                subprocess.run(
                    ["pkill", "-f", pattern], capture_output=True, text=True
                )


def restart_shell(root: Path) -> None:
    config = root / "config/quickshell"

    if systemd_user_available():
        try:
            active = subprocess.run(
                ["systemctl", "--user", "is-active", "--quiet", "kolir-shell.service"],
                timeout=10,
            )
        except (OSError, subprocess.SubprocessError):
            active = None
        if active is not None and active.returncode == 0:
            result = subprocess.run(
                ["systemctl", "--user", "restart", "kolir-shell.service"],
                capture_output=True,
                text=True,
            )
            if result.returncode == 0:
                ok("restarted kolir-shell.service")
            else:
                warn(
                    "could not restart kolir-shell.service: "
                    + (result.stderr.strip() or "unknown error")
                )
            return

    if not graphical_session_available():
        warn(
            "no Wayland/graphical session in this environment; "
            "skipped the Quickshell restart"
        )
        return

    qs = shutil.which("qs")
    if not qs:
        warn("qs is not installed; cannot restart Quickshell")
        return

    kill_other_shells(qs, config)
    time.sleep(0.7)

    log_path = cache_home() / "kolir/shell.log"
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with log_path.open("ab") as log:
        try:
            subprocess.Popen(
                [qs, "-p", str(config)],
                stdin=subprocess.DEVNULL,
                stdout=log,
                stderr=subprocess.STDOUT,
                start_new_session=True,
                cwd=str(root),
            )
        except OSError as exc:
            warn(f"could not relaunch Quickshell: {exc}")
            return
    ok(f"restarted Quickshell (log: {log_path})")


def cmd_reload(args: argparse.Namespace) -> int:
    try:
        root = require_root()
    except SetupError as exc:
        error(str(exc))
        return 1

    status = 0

    if args.colors:
        script = root / "config/hypr/scripts/generate-colors.sh"
        if not script.is_file():
            error(f"generate-colors.sh is missing: {script}")
            status = 1
        else:
            zsh = shutil.which("zsh")
            if not zsh:
                error("zsh is missing; cannot run generate-colors.sh")
                status = 1
            else:
                info(f"regenerating colors with {script}")
                result = subprocess.run([zsh, str(script)], cwd=str(root))
                if result.returncode != 0:
                    error("generate-colors.sh failed; colors were not refreshed")
                    status = 1
                else:
                    ok("colors regenerated")

    if not hyprland_running():
        warn("Hyprland is not available; skipped 'hyprctl reload'")
    else:
        result = subprocess.run(["hyprctl", "reload"], capture_output=True, text=True)
        if result.returncode != 0:
            warn(
                "hyprctl reload failed: "
                + (result.stderr.strip() or result.stdout.strip() or "unknown error")
            )
        else:
            ok("Hyprland reloaded")

    if args.no_shell:
        info("Quickshell restart skipped (--no-shell)")
    else:
        restart_shell(root)

    return status


