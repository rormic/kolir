def setup_portal(deploy: Deployer, root: Path) -> None:
    """Install the user-level XDG Desktop Portal FileChooser backend glue."""
    script = root / PORTAL_SCRIPT_REL
    if not script.is_file():
        raise SetupError(
            f"'{script}' is missing; the checkout is incomplete."
        )

    deploy.ensure_file(portal_portal_path(), portal_portal_text())
    deploy.ensure_file(portal_service_path(), portal_service_text(root))
    config = portal_config_path()
    deploy.ensure_file_if_absent(config, portal_config_text())

    if config.is_file():
        try:
            text = config.read_text(encoding="utf-8")
        except OSError:
            text = ""
        if f"FileChooser={PORTAL_IMPL_NAME}" not in text:
            deploy.note(
                f"portal: {config} exists but does not select "
                f"'{PORTAL_IMPL_NAME}'; add "
                f"'org.freedesktop.impl.portal.FileChooser={PORTAL_IMPL_NAME}' "
                "under [preferred]"
            )

    # The session bus caches D-Bus service files; a reload makes the new
    # backend activatable without a logout.  Best effort only.
    if not deploy.dry_run and shutil.which("busctl"):
        subprocess.run(
            [
                "busctl", "--user", "call", "org.freedesktop.DBus",
                "/org/freedesktop/DBus", "org.freedesktop.DBus",
                "ReloadConfig",
            ],
            capture_output=True,
            text=True,
        )

    deploy.note(
        "portal: restart xdg-desktop-portal after setup to load the backend "
        "(systemctl --user restart xdg-desktop-portal.service)"
    )


