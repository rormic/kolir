def cmd_setup(args: argparse.Namespace) -> int:
    if os.geteuid() == 0:
        error("refusing to run as root; run 'kolir setup' as your desktop user.")
        return 1

    try:
        root = require_root()
        if not (root / MATUGEN_CONFIG_REL).is_file():
            raise SetupError(
                f"'{root}' is missing {MATUGEN_CONFIG_REL}; the checkout is incomplete."
            )

        obsidian_output = decide_obsidian(args)

        if (
            not args.yes
            and sys.stdin.isatty()
            and not ask_yes_no(
                "Create the kolir user glue under ~/.config (existing files are backed up)?",
                default=True,
            )
        ):
            warn("cancelled by user; no changes made.")
            return 0

        deploy = Deployer(root, dry_run=args.dry_run, force=args.force)
        step("Deploying kolir user glue")
        info(f"root: {root}")
        if args.dry_run:
            info("dry run: nothing will be written")

        setup_directories(deploy)
        setup_hyprland(deploy, root)
        setup_foot(deploy, root)
        setup_matugen(deploy, root, obsidian_output)
        setup_misc(deploy, root)
        if args.zsh:
            setup_zsh(deploy, root)
        else:
            deploy.note("zsh: skipped ~/.zshrc (pass --zsh to link it)")

        deploy.ensure_version()
        enable_idle_service(deploy, args.no_systemd)

        if args.auto_reload:
            install_reload_units(deploy, args.no_systemd)
        else:
            deploy.note(
                "auto-reload: not installed (pass --auto-reload to enable the user units)"
            )

        print_setup_summary(deploy, args)
        return 0
    except SetupError as exc:
        error(str(exc))
        return 1


