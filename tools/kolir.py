def normalize_obsidian_output(value: str, explicit_file: bool = False) -> str:
    raw = value.strip()
    if not raw:
        raise SetupError(
            "Obsidian theming requires a path; pass a vault directory or a .css file."
        )
    candidate = Path(os.path.expanduser(raw))
    if explicit_file or candidate.suffix.lower() == ".css" or (
        candidate.exists() and candidate.is_file()
    ):
        output = candidate
    else:
        output = candidate / ".obsidian" / "snippets" / OBSIDIAN_FILENAME
    if not output.is_absolute():
        output = Path.cwd() / output
    return os.path.normpath(str(output))


def ask_yes_no(prompt: str, default: bool = True) -> bool:
    suffix = "[Y/n]" if default else "[y/N]"
    try:
        reply = input(f"{prompt} {suffix} ").strip().lower()
    except EOFError:
        return default
    if not reply:
        return default
    return reply in ("y", "yes")


def decide_obsidian(args: argparse.Namespace) -> str | None:
    if args.no_obsidian:
        return None
    if args.obsidian_output:
        return normalize_obsidian_output(args.obsidian_output, explicit_file=True)
    if args.obsidian:
        return normalize_obsidian_output(args.obsidian)

    if args.yes or not sys.stdin.isatty():
        info(
            "obsidian: theming skipped (pass --obsidian <vault|file> to enable it)"
        )
        return None

    if not ask_yes_no("Enable Obsidian theming?", default=False):
        return None

    for _attempt in range(3):
        try:
            reply = input("Obsidian vault directory or .css output path: ").strip()
        except EOFError:
            reply = ""
        if reply:
            return normalize_obsidian_output(reply)
        error(
            "Obsidian theming was enabled, so a path is required. "
            "Enter a vault directory or a .css file."
        )
    raise SetupError(
        "Obsidian theming was requested but no path was provided; nothing was changed."
    )


