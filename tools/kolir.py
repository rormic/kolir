def is_under(path: str, root: Path) -> bool:
    try:
        Path(path).relative_to(root)
        return True
    except ValueError:
        return False


def remove_managed_link(report: Report, path: Path, root: Path, dry_run: bool) -> bool:
    """Remove path only when it is a symlink that still points into root."""
    if not path.is_symlink():
        return False
    raw_target = lexical_link_target(path)
    resolved = os.path.realpath(path)
    if not (is_under(raw_target, root) or is_under(resolved, root)):
        report.note(f"left {path} (points outside {root}: {raw_target})")
        return False
    if dry_run:
        info(f"would remove symlink {path} -> {raw_target}")
    else:
        path.unlink()
        info(f"removed symlink {path} -> {raw_target}")
    return True


def cmd_uninstall_user(args: argparse.Namespace) -> int:
    try:
        root = require_root()
    except SetupError as exc:
        error(str(exc))
        return 1

    dry_run = args.dry_run
    report = Report()
    removed: list[str] = []
    home = home_dir()

    step("Removing kolir user glue")
    managed_links = [
        config_home() / "hypr/hyprland.lua",
        config_home() / "hypr/scripts",
        config_home() / "hypr/hyprsunset.conf",
        config_home() / "hypr/hyprlock.conf",
        config_home() / "hypr/hypridle.conf",
        config_home() / "matugen/hyprlock.toml",
        config_home() / "mpv/mpv.conf",
        zsh_custom_dir() / "themes/dice.zsh-theme",
    ]
    templates = config_home() / "matugen/templates"
    if templates.is_symlink():
        managed_links.append(templates)

    for path in managed_links:
        if remove_managed_link(report, path, root, dry_run):
            removed.append(str(path))

    zshrc = home / ".zshrc"

    loader = config_home() / "foot/foot.ini"
    if loader.is_file() and not loader.is_symlink():
        try:
            text = loader.read_text(encoding="utf-8")
        except OSError:
            text = ""
        if text == foot_loader_text(root):
            if dry_run:
                info(f"would remove managed foot loader {loader}")
            else:
                loader.unlink()
                info(f"removed managed foot loader {loader}")
            removed.append(str(loader))
        else:
            report.note(f"left {loader} (content is not the managed loader)")
    elif os.path.lexists(loader):
        report.note(f"left {loader} (not a regular managed loader)")

    service_unit = unit_dir() / "kolir-reload.service"
    path_unit = unit_dir() / "kolir-reload.path"
    managed_units = [
        unit for unit in (service_unit, path_unit)
        if unit.is_file()
        and UNIT_MARKER in unit.read_text(encoding="utf-8", errors="replace")
        and str(root) in unit.read_text(encoding="utf-8", errors="replace")
    ]
    if managed_units:
        if not dry_run and systemd_user_available():
            subprocess.run(
                ["systemctl", "--user", "disable", "--now", "kolir-reload.path"],
                capture_output=True,
                text=True,
            )
        for unit in managed_units:
            if dry_run:
                info(f"would remove managed unit {unit}")
            else:
                unit.unlink()
                info(f"removed managed unit {unit}")
            removed.append(str(unit))
        if not dry_run and systemd_user_available():
            subprocess.run(
                ["systemctl", "--user", "daemon-reload"],
                capture_output=True,
                text=True,
            )
    elif path_unit.is_file() or service_unit.is_file():
        report.note(
            "left the auto-reload units (they were not generated by kolir setup)"
        )

    step("Left in place")
    removed_set = set(removed)
    left = [
        config_home() / "hypr/user.lua",
        config_home() / "hypr/hyprlock-colors.conf",
        config_home() / "hypr/colors.lua",
        config_home() / "matugen/config.toml",
        templates,
        config_home() / "foot/colors.ini",
        config_home() / "quickshell/colors.json",
        cache_home() / "current_theme",
        config_home() / "gtk-3.0/gtk.css",
        config_home() / "gtk-4.0/gtk.css",
        zshrc,
    ]
    for path in left:
        if not os.path.lexists(path) or str(path) in removed_set:
            continue
        if path == zshrc and path.is_symlink() and is_under(
            lexical_link_target(path), root
        ):
            report.note(
                f"kept {path} (user-owned; it points into this root, "
                "restore a .zshrc.bak.* backup if you delete the checkout)"
            )
        else:
            report.note(f"kept {path}")

    step("Summary")
    if removed:
        if dry_run:
            ok(f"dry run: {len(removed)} item(s) would be removed.")
        else:
            ok(f"removed {len(removed)} item(s).")
    else:
        ok("nothing to remove; no user glue points into this root.")
    report.note(
        "user.lua, the matugen config, generated colors, and backups are user-owned "
        "and were left alone."
    )
    report.note(
        "backups created by 'kolir setup' (.bak.*) are never deleted automatically."
    )
    return 0


