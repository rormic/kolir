def current_git_ref(root: Path) -> Path | None:
    git_dir = root / ".git"
    if not git_dir.is_dir():
        return None
    head = git_dir / "HEAD"
    try:
        head_text = head.read_text(encoding="utf-8").strip()
    except OSError:
        return None
    if head_text.startswith("ref: "):
        branch_ref = git_dir / head_text[5:].strip()
        if branch_ref.is_file():
            return branch_ref
    if head.is_file():
        return head
    return None


def reload_cli_command(root: Path) -> str:
    """Use the checkout CLI when present, otherwise the installed entry point."""
    checkout_cli = root / "tools/kolir.py"
    if checkout_cli.is_file():
        return f'python3 "{checkout_cli}"'
    installed = shutil.which("kolir")
    if installed:
        return f'"{installed}"'
    return f'python3 "{checkout_cli}"'


def render_reload_units(root: Path) -> tuple[str, str]:
    watched = [root / VERSION_FILE]
    git_ref = current_git_ref(root)
    if git_ref is not None:
        watched.append(git_ref)
    watched_lines = "\n".join(f"PathChanged={path}" for path in watched)

    service = (
        f"{UNIT_MARKER}; rerun 'kolir setup --auto-reload' after moving the checkout\n"
        "[Unit]\n"
        "Description=Reload the kolir session after a checkout update\n"
        "\n"
        "[Service]\n"
        "Type=oneshot\n"
        f"ExecStart={reload_cli_command(root)} reload\n"
    )

    path_unit = (
        f"{UNIT_MARKER}; rerun 'kolir setup --auto-reload' after moving the checkout\n"
        "[Unit]\n"
        "Description=Watch the kolir checkout and .version for updates\n"
        "\n"
        "[Path]\n"
        f"{watched_lines}\n"
        "Unit=kolir-reload.service\n"
        "\n"
        "[Install]\n"
        "WantedBy=default.target\n"
    )
    return service, path_unit


def systemd_user_available() -> bool:
    if not shutil.which("systemctl"):
        return False
    try:
        result = subprocess.run(
            ["systemctl", "--user", "show-environment"],
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        return False
    return result.returncode == 0


def verify_units(units: list[Path]) -> list[str]:
    tool = shutil.which("systemd-analyze")
    if not tool:
        return []
    try:
        result = subprocess.run(
            [tool, "--user", "verify", *[str(unit) for unit in units]],
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return []
    if result.returncode == 0:
        return []
    output = (result.stderr or result.stdout).strip().splitlines()
    return output


def enable_idle_service(deploy: Deployer, no_systemd: bool) -> None:
    """Enable hypridle.service, as the old installer did, unless asked not to."""
    if no_systemd:
        deploy.note("systemd: skipped enabling hypridle.service (--no-systemd)")
        return
    if deploy.dry_run:
        deploy.note("would enable hypridle.service")
        return
    if not systemd_user_available():
        deploy.note(
            "no systemd user manager; enable hypridle.service later with "
            "'systemctl --user enable --now hypridle.service'"
        )
        return
    result = subprocess.run(
        ["systemctl", "--user", "enable", "--now", "hypridle.service"],
        capture_output=True,
        text=True,
    )
    if result.returncode == 0:
        ok("enabled hypridle.service")
    else:
        warn(
            "could not enable hypridle.service: "
            + (result.stderr.strip() or result.stdout.strip() or "unknown error")
        )


def install_reload_units(deploy: Deployer, no_systemd: bool) -> None:
    root = deploy.root
    service_text, path_text = render_reload_units(root)
    user_units = unit_dir()
    service_path = user_units / "kolir-reload.service"
    path_path = user_units / "kolir-reload.path"

    changed_before = len(deploy.changes)
    deploy.ensure_dir(user_units)
    deploy.ensure_file(service_path, service_text)
    deploy.ensure_file(path_path, path_text)
    units_changed = len(deploy.changes) > changed_before

    if deploy.dry_run:
        deploy.note("dry run: systemd actions skipped")
        return

    problems = verify_units([path_path, service_path])
    if problems:
        warn("systemd-analyze reported unit problems:")
        for line in problems[:8]:
            warn("  " + line)

    if no_systemd:
        deploy.note("systemd actions skipped (--no-systemd); units were written only")
        return

    if not systemd_user_available():
        deploy.note(
            "no systemd user manager is available; units were written but not enabled. "
            "Run 'systemctl --user daemon-reload && systemctl --user enable --now kolir-reload.path' later."
        )
        return

    if units_changed:
        result = subprocess.run(
            ["systemctl", "--user", "daemon-reload"],
            capture_output=True,
            text=True,
        )
        if result.returncode != 0:
            warn(f"systemctl --user daemon-reload failed: {result.stderr.strip()}")

    result = subprocess.run(
        ["systemctl", "--user", "enable", "--now", "kolir-reload.path"],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        warn(
            "could not enable kolir-reload.path: "
            + (result.stderr.strip() or result.stdout.strip() or "unknown error")
        )
    else:
        ok("enabled kolir-reload.path")


