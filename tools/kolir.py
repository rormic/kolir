class Report:
    def __init__(self) -> None:
        self.errors = 0
        self.warnings = 0

    def ok(self, message: str) -> None:
        print(f"  {_paint('32', 'ok')}    {message}")

    def warn(self, message: str) -> None:
        self.warnings += 1
        print(f"  {_paint('33', 'warn')}  {message}")

    def error(self, message: str) -> None:
        self.errors += 1
        print(f"  {_paint('31', 'error')} {message}")

    def note(self, message: str) -> None:
        print(f"  {_paint('34', 'info')}  {message}")


def command_available(candidates: tuple[str, ...]) -> str | None:
    for name in candidates:
        found = shutil.which(name)
        if found:
            return found
    return None


def check_commands(report: Report) -> None:
    step("Commands")
    for command, purpose, package in REQUIRED_COMMANDS:
        if shutil.which(command):
            report.ok(f"{command} ({purpose})")
        else:
            report.error(f"{command} is missing ({package}); {purpose} will not work")

    for candidates, purpose, package in OPTIONAL_CHECKS:
        found = command_available(candidates)
        label = "/".join(candidates)
        if found:
            report.ok(f"{label} ({purpose})")
        else:
            report.warn(
                f"{label} is missing (optional, {package}); {purpose} is disabled"
            )

    icon_root = Path("/usr/share/icons")
    if icon_root.is_dir() and list(icon_root.glob("Mocu*")):
        report.ok("Mocu cursor theme (mocu-xcursor)")
    else:
        report.warn(
            "Mocu cursor theme is missing (optional, mocu-xcursor); "
            "the user.lua cursor setting falls back to the default theme"
        )


def check_symlink(report: Report, label: str, path: Path, target: Path) -> None:
    if path.is_symlink():
        actual = os.path.realpath(path)
        expected = os.path.realpath(target)
        if actual == expected:
            report.ok(f"{label}: {path} -> {target}")
        else:
            report.error(
                f"{label}: {path} points to {actual}; expected {target} (rerun kolir setup)"
            )
    elif os.path.lexists(path):
        report.error(f"{label}: {path} is not a symlink (rerun kolir setup)")
    else:
        report.error(f"{label}: missing {path} (run kolir setup)")


def expand_matugen_path(value: str, config_path: Path) -> Path:
    expanded = os.path.expanduser(value)
    if not os.path.isabs(expanded):
        expanded = os.path.join(str(config_path.parent), expanded)
    return Path(os.path.normpath(expanded))


def check_deployment(report: Report, root: Path) -> None:
    step("Deployment")
    hypr = config_home() / "hypr"

    check_symlink(
        report, "hyprland.lua", hypr / "hyprland.lua",
        root / "config/hypr/hyprland.lua",
    )
    check_symlink(
        report, "hypr scripts", hypr / "scripts", root / "config/hypr/scripts"
    )
    check_symlink(
        report, "hyprsunset.conf", hypr / "hyprsunset.conf",
        root / "config/hypr/hyprsunset.conf",
    )
    check_symlink(
        report, "hyprlock.conf", hypr / "hyprlock.conf",
        root / "config/hypr/hyprlock.conf",
    )
    check_symlink(
        report, "hypridle.conf", hypr / "hypridle.conf",
        root / "config/hypr/hypridle.conf",
    )
    check_symlink(
        report, "matugen hyprlock.toml", config_home() / "matugen/hyprlock.toml",
        root / "config/matugen/hyprlock.toml",
    )
