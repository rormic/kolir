def check_matugen_config(report: Report) -> None:
    step("Matugen")
    config_path = config_home() / "matugen/config.toml"
    if not config_path.is_file():
        report.error(f"matugen: cannot read {config_path}")
        return
    try:
        with config_path.open("rb") as handle:
            config = tomllib.load(handle)
    except (OSError, tomllib.TOMLDecodeError) as exc:
        report.error(f"matugen: cannot parse {config_path}: {exc}")
        return

    templates = config.get("templates", {})
    if not isinstance(templates, dict) or not templates:
        report.error(f"matugen: {config_path} defines no [templates.*] entries")
        return

    for name, template in templates.items():
        if not isinstance(template, dict):
            report.warn(f"matugen: template '{name}' is not a table")
            continue
        input_value = template.get("input_path")
        if not isinstance(input_value, str) or not input_value.strip():
            report.warn(f"matugen: template '{name}' has no input_path")
            continue
        input_path = expand_matugen_path(input_value, config_path)
        if input_path.is_file() and os.access(input_path, os.R_OK):
            report.ok(f"matugen input '{name}': {input_path}")
        else:
            report.error(f"matugen input '{name}' is missing: {input_path}")

        output_value = template.get("output_path")
        if (
            name != "obsidian"
            and isinstance(output_value, str)
            and output_value.strip()
        ):
            output_path = expand_matugen_path(output_value, config_path)
            if not output_path.parent.is_dir():
                report.warn(
                    f"matugen output '{name}': parent directory is missing: "
                    f"{output_path.parent} (matugen cannot write {output_path})"
                )

    obsidian = templates.get("obsidian")
    if isinstance(obsidian, dict):
        output_value = obsidian.get("output_path")
        if isinstance(output_value, str) and output_value.strip():
            output_path = expand_matugen_path(output_value, config_path)
            if output_path.parent.is_dir():
                report.ok(f"obsidian: writes to {output_path}")
            else:
                report.warn(
                    f"obsidian: output directory is missing: {output_path.parent} "
                    "(create the vault or rerun 'kolir setup --obsidian <vault>')"
                )
        else:
            report.warn("obsidian: [templates.obsidian] has no output_path")
    else:
        report.note(
            "obsidian: theming not configured (optional; rerun "
            "'kolir setup --obsidian <vault>')"
        )


def hyprland_option(hyprctl: str, option: str) -> str | None:
    """Return the value reported by `hyprctl getoption` for a bool option."""
    try:
        result = subprocess.run(
            [hyprctl, "getoption", option],
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if result.returncode != 0:
        return None
    for line in (result.stdout or "").splitlines():
        line = line.strip()
        if line.startswith("bool:"):
            return line.split(":", 1)[1].strip()
    return None


def check_hyprland(report: Report) -> None:
    step("Hyprland")
    hyprctl = shutil.which("hyprctl")
    if not hyprctl:
        report.warn("hyprctl is missing; skipped Hyprland checks")
        return
    try:
        probe = subprocess.run(
            [hyprctl, "-j", "monitors"],
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        probe = None
    if probe is None or probe.returncode != 0:
        report.warn("no live Hyprland instance; skipped hyprctl configerrors")
        return

    try:
        result = subprocess.run(
            [hyprctl, "configerrors"],
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        report.warn(f"could not run hyprctl configerrors: {exc}")
        return
    output = (result.stdout or "").strip()
    if output:
        report.error(f"Hyprland config errors:\n{output}")
    else:
        report.ok("hyprctl configerrors is empty")

    logo = hyprland_option(hyprctl, "misc:disable_hyprland_logo")
    if logo == "true":
        report.ok("desktop background: awww only (disable_hyprland_logo = true)")
    elif logo == "false":
        report.warn(
            "misc:disable_hyprland_logo is false; Hyprland still paints its "
            "logo/anime background under the awww wallpaper. Check that "
            "~/.config/hypr/hyprland.lua links to the kolir root and run "
            "'hyprctl reload'"
        )
    else:
        report.note("could not read misc:disable_hyprland_logo; skipped the check")


def check_quickshell(report: Report, root: Path) -> None:
    step("Quickshell")
    qs = shutil.which("qs")
    if not qs:
        report.warn("qs is missing; skipped the running-instance check")
        return
    try:
        result = subprocess.run(
            [qs, "list", "--all"], capture_output=True, text=True, timeout=10
        )
    except (OSError, subprocess.SubprocessError) as exc:
        report.warn(f"could not run 'qs list --all': {exc}")
        return
    text = (result.stdout or "").strip()
    if not text or "No running instances" in text:
        report.note("no running Quickshell instance")
        return
    if text.startswith("Could not find") or "Could not find" in text:
        report.note("no running Quickshell instance")
        return
    report.ok("running Quickshell instances:")
    for line in text.splitlines():
        report.note("  " + line)


def check_systemd(report: Report) -> None:
    step("Auto-reload")
    path_unit = unit_dir() / "kolir-reload.path"
    service_unit = unit_dir() / "kolir-reload.service"
    if not path_unit.is_file() and not service_unit.is_file():
        report.note(
            "units not installed (optional; rerun 'kolir setup --auto-reload')"
        )
        return
    for unit in (service_unit, path_unit):
        if unit.is_file():
            report.ok(f"unit: {unit}")
        else:
            report.warn(f"auto-reload unit is missing: {unit}")
    if not systemd_user_available():
        report.warn("no systemd user manager; cannot report the unit state")
        return
    try:
        result = subprocess.run(
            ["systemctl", "--user", "is-enabled", "kolir-reload.path"],
            capture_output=True,
            text=True,
            timeout=10,
        )
    except (OSError, subprocess.SubprocessError):
        report.warn("could not query kolir-reload.path")
        return
    state = (result.stdout or "").strip() or "unknown"
    if result.returncode == 0:
        report.ok(f"kolir-reload.path: {state}")
    else:
        report.warn(f"kolir-reload.path: {state}")


def check_user_services(report: Report) -> None:
    step("User services")
    if not systemd_user_available():
        report.warn(
            "no systemd user manager; cannot report "
            + ", ".join(unit for unit, _, _ in SESSION_SERVICES)
        )
        return
    for unit, command, purpose in SESSION_SERVICES:
        if not shutil.which(command):
            report.warn(f"{unit}: '{command}' is not installed ({purpose})")
            continue
        try:
            enabled = subprocess.run(
                ["systemctl", "--user", "is-enabled", unit],
                capture_output=True,
                text=True,
                timeout=10,
            )
            active = subprocess.run(
                ["systemctl", "--user", "is-active", unit],
                capture_output=True,
                text=True,
                timeout=10,
            )
        except (OSError, subprocess.SubprocessError):
            report.warn(f"could not query {unit}")
            continue
        if enabled.returncode != 0:
            report.warn(
                f"{unit} is not enabled (run 'kolir setup' or "
                f"'systemctl --user enable --now {unit}')"
            )
        elif active.returncode != 0:
            report.warn(f"{unit} is enabled but not active")
        else:
            report.ok(f"{unit} is enabled and active")


