def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog=PROGRAM,
        description="Set up and control the kolir desktop (phase 1: no packaging).",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    setup = sub.add_parser(
        "setup", help="create or refresh the per-user glue under ~/.config"
    )
    setup.add_argument(
        "--dry-run", action="store_true",
        help="print every change without writing anything",
    )
    setup.add_argument(
        "--force", action="store_true",
        help="recreate managed symlinks/files even when they already look correct",
    )
    setup.add_argument(
        "-y", "--yes", action="store_true",
        help="do not ask for confirmation; skip the interactive Obsidian question",
    )
    setup.add_argument(
        "--no-systemd", action="store_true",
        help="write the auto-reload units but skip systemctl actions",
    )
    setup.add_argument(
        "--auto-reload", action="store_true",
        help="install and enable the systemd user path/service units",
    )
    setup.add_argument(
        "--zsh", action="store_true",
        help="link ~/.zshrc and the dice Oh My Zsh theme (off by default)",
    )
    obsidian = setup.add_mutually_exclusive_group()
    obsidian.add_argument(
        "--obsidian", metavar="VAULT_OR_CSS",
        help="enable Obsidian theming for this vault directory or .css file",
    )
    obsidian.add_argument(
        "--obsidian-output", metavar="FILE",
        help="enable Obsidian theming writing to this .css file",
    )
    obsidian.add_argument(
        "--no-obsidian", action="store_true",
        help="skip Obsidian theming even if an entry already exists",
    )
    setup.set_defaults(func=cmd_setup)

    doctor = sub.add_parser("doctor", help="check the installation")
    doctor.set_defaults(func=cmd_doctor)

    reload = sub.add_parser("reload", help="reload Hyprland and restart the shell")
    reload.add_argument(
        "--colors", action="store_true", help="run generate-colors.sh first"
    )
    reload.add_argument(
        "--no-shell", action="store_true", help="do not restart Quickshell"
    )
    reload.set_defaults(func=cmd_reload)

    shell = sub.add_parser("shell", help="exec qs with the checkout config")
    shell.add_argument("args", nargs=argparse.REMAINDER, help="arguments passed to qs")
    shell.set_defaults(func=cmd_shell)

    ipc = sub.add_parser("ipc", help="forward 'qs ipc call' to the running shell")
    ipc.add_argument("parts", nargs=argparse.REMAINDER)
    ipc.set_defaults(func=cmd_ipc)

    version = sub.add_parser("version", help="print the checkout/package version")
    version.set_defaults(func=cmd_version)

    uninstall = sub.add_parser(
        "uninstall-user", help="remove only the glue created by 'kolir setup'"
    )
    uninstall.add_argument(
        "--dry-run", action="store_true", help="report what would be removed"
    )
    uninstall.set_defaults(func=cmd_uninstall_user)

    return parser


def main(argv: list[str] | None = None) -> int:
    raw = list(sys.argv[1:] if argv is None else argv)
    # `shell` and `ipc` forward every argument verbatim, including flags that
    # argparse would otherwise consume.
    if len(raw) > 1 and raw[0] == "shell":
        return cmd_shell(argparse.Namespace(args=raw[1:]))
    if len(raw) > 1 and raw[0] == "ipc":
        return cmd_ipc(argparse.Namespace(parts=raw[1:]))

    parser = build_parser()
    args = parser.parse_args(raw)
    try:
        return args.func(args)
    except SetupError as exc:
        error(str(exc))
        return 1
    except KeyboardInterrupt:
        error("interrupted")
        return 130


if __name__ == "__main__":
    sys.exit(main())
