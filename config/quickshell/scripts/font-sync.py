#!/usr/bin/env python3
"""Apply the Settings → Fonts choices to the programs outside Quickshell.

The shell owns the choice (FontService persists it in
~/.cache/quickshell/fonts.json); this one-shot helper only renders it:

    font-sync.py list
    font-sync.py apply --ui FAMILY --terminal FAMILY
                       [--foot on|off] [--obsidian on|off] [--clean-obsidian]

`list` prints the installed families from fontconfig as one JSON object:

    {"ok": true, "fonts": [{"family": "Inter", "mono": false}, ...]}

`apply` writes the parts the user asked for and prints one JSON object:

  * ~/.config/foot/font.ini                 terminal font (new Foot windows)
  * ~/.config/foot/foot.ini                 adds the font.ini include when the
                                            loader is managed by kolir setup
  * <vault>/.obsidian/snippets/kolir-font.css  interface + code fonts in Obsidian
  * <vault>/.obsidian/appearance.json       enables that snippet

Only `--foot on` touches the Foot files, so an untouched font choice never
overwrites a hand-written Foot config. Obsidian is only changed with
`--obsidian on`; `--clean-obsidian` removes the generated snippet when the
switch is turned off. The lock screen is deliberately not a target: its mixed
Google Sans Flex clock depends on that family's width and round instances.
Every failure is reported in the JSON object and exit status 1, so the Fonts
page can explain it.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

MARKER = "# Generated by kolir Fonts"
FOOT_FONT = Path("~/.config/foot/font.ini")
FOOT_LOADER = Path("~/.config/foot/foot.ini")
FOOT_LOADER_MARKER = "# Managed by kolir setup"
MATUGEN_CONFIG = Path("~/.config/matugen/config.toml")
OBSIDIAN_STATE = Path("~/.config/obsidian/obsidian.json")
OBSIDIAN_SNIPPET = "kolir-font"
FONT_SIZE = "9.375"
FALLBACK_MONO = "DejaVu Sans Mono"
ICON_FAMILIES = ("Material Symbols", "Material Icons", "Noto Color Emoji")


def fail(message: str) -> int:
    print(json.dumps({"ok": False, "error": message}, ensure_ascii=False))
    return 1


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    os.replace(temporary, path)


def clean_family(value: str) -> str:
    family = " ".join(str(value).split())
    if not family:
        raise ValueError("font family must not be empty")
    return family


def list_fonts() -> list[dict]:
    try:
        result = subprocess.run(
            ["fc-list", "--format", "%{family[0]}\t%{spacing}\t%{style[0]}\n"],
            capture_output=True,
            text=True,
            timeout=20,
        )
    except (OSError, subprocess.SubprocessError):
        return []

    fonts: dict[str, dict] = {}
    for line in result.stdout.splitlines():
        parts = line.split("\t")
        family = parts[0].strip() if parts else ""
        if not family:
            continue
        spacing = parts[1].strip() if len(parts) > 1 else ""
        mono = spacing in {"90", "100", "110"}
        if family.startswith(ICON_FAMILIES):
            mono = False
        key = family.casefold()
        entry = fonts.get(key)
        if entry is None:
            fonts[key] = {"family": family, "mono": mono}
        elif mono:
            entry["mono"] = True

    return sorted(fonts.values(), key=lambda entry: entry["family"].casefold())


def foot_text(family: str) -> str:
    regular_fallback = (
        f", {FALLBACK_MONO}:size={FONT_SIZE}"
        if family != FALLBACK_MONO
        else ""
    )
    bold_fallback = (
        f", {FALLBACK_MONO}:style=Bold:size={FONT_SIZE}"
        if family != FALLBACK_MONO
        else ""
    )
    italic_fallback = (
        f", {FALLBACK_MONO}:style=Italic:size={FONT_SIZE}"
        if family != FALLBACK_MONO
        else ""
    )
    return (
        f"{MARKER}; edit through Settings → Fonts.\n"
        f"font={family}:size={FONT_SIZE}{regular_fallback}\n"
        f"font-bold={family}:style=Bold:size={FONT_SIZE}{bold_fallback}\n"
        f"font-italic={family}:style=Regular Italic:size={FONT_SIZE}"
        f"{italic_fallback}\n"
    )


def ensure_foot_include() -> dict:
    loader = FOOT_LOADER.expanduser()
    font = FOOT_FONT.expanduser()
    if not loader.is_file():
        return {
            "ok": False,
            "path": str(loader),
            "error": f"{loader} is missing; run 'kolir setup'",
        }

    try:
        text = loader.read_text(encoding="utf-8")
    except OSError as error:
        return {"ok": False, "path": str(loader), "error": str(error)}

    include = f"include={font}"
    if include in text or "include=~/.config/foot/font.ini" in text:
        return {"ok": True, "path": str(loader)}

    if not text.startswith(FOOT_LOADER_MARKER):
        return {
            "ok": False,
            "path": str(loader),
            "error": f"{loader} is not managed by kolir; add "
            f"'{include}' by hand",
        }

    if not text.endswith("\n"):
        text += "\n"
    try:
        atomic_write(loader, text + include + "\n")
    except OSError as error:
        return {"ok": False, "path": str(loader), "error": str(error)}
    return {"ok": True, "path": str(loader)}


def write_foot(family: str) -> dict:
    path = FOOT_FONT.expanduser()
    text = foot_text(family)
    try:
        current = path.read_text(encoding="utf-8") if path.is_file() else ""
        if current != text:
            atomic_write(path, text)
    except OSError as error:
        return {"ok": False, "path": str(path), "error": str(error)}

    included = ensure_foot_include()
    return {
        "ok": bool(included.get("ok")),
        "path": str(path),
        "loader": included,
    }


def vault_from_obsidian_state() -> Path | None:
    try:
        data = json.loads(OBSIDIAN_STATE.expanduser().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None

    vaults = data.get("vaults")
    if not isinstance(vaults, dict):
        return None

    entries = [entry for entry in vaults.values() if isinstance(entry, dict)]
    entries.sort(
        key=lambda entry: (bool(entry.get("open")), entry.get("ts") or 0),
        reverse=True,
    )
    for entry in entries:
        raw = entry.get("path")
        if not isinstance(raw, str) or not raw:
            continue
        vault = Path(os.path.expanduser(raw))
        if vault.is_dir():
            return vault
    return None


def vault_from_matugen() -> Path | None:
    try:
        import tomllib
    except ImportError:  # pragma: no cover - Python older than 3.11
        return None

    try:
        data = tomllib.loads(MATUGEN_CONFIG.expanduser().read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None

    templates = data.get("templates")
    obsidian = templates.get("obsidian") if isinstance(templates, dict) else None
    output = obsidian.get("output_path") if isinstance(obsidian, dict) else None
    if not isinstance(output, str) or not output:
        return None

    target = Path(os.path.expanduser(output))
    for parent in target.parents:
        if (parent / ".obsidian").is_dir():
            return parent
    return None


def find_vault() -> tuple[Path | None, str]:
    env_vault = os.environ.get("KOLIR_OBSIDIAN_VAULT", "").strip()
    if env_vault:
        vault = Path(os.path.expanduser(env_vault))
        if vault.is_dir():
            return vault, ""
        return None, f"Obsidian vault not found: {vault}"

    vault = vault_from_obsidian_state() or vault_from_matugen()
    if vault:
        return vault, ""

    return None, (
        "Obsidian vault not found: open one in Obsidian, set "
        "KOLIR_OBSIDIAN_VAULT, or run 'kolir setup --obsidian <vault>'"
    )


def set_snippet_enabled(vault: Path, enabled: bool) -> dict:
    appearance = vault / ".obsidian" / "appearance.json"
    data: dict = {}
    if appearance.is_file():
        try:
            loaded = json.loads(appearance.read_text(encoding="utf-8"))
        except (OSError, ValueError) as error:
            return {"ok": False, "error": f"cannot read {appearance}: {error}"}
        if isinstance(loaded, dict):
            data = loaded

    snippets = data.get("enabledCssSnippets")
    if not isinstance(snippets, list):
        snippets = []

    changed = False
    if enabled and OBSIDIAN_SNIPPET not in snippets:
        snippets.append(OBSIDIAN_SNIPPET)
        changed = True
    elif not enabled and OBSIDIAN_SNIPPET in snippets:
        snippets.remove(OBSIDIAN_SNIPPET)
        changed = True

    if changed:
        data["enabledCssSnippets"] = snippets
        try:
            atomic_write(
                appearance,
                json.dumps(data, indent=2, ensure_ascii=False) + "\n",
            )
        except OSError as error:
            return {"ok": False, "error": str(error)}
    return {"ok": True}


def obsidian_css(ui: str, terminal: str) -> str:
    def quote(value: str) -> str:
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'

    return (
        "/* Generated by kolir Fonts; edit through Settings → Fonts. */\n"
        "body {\n"
        f"  --font-interface-theme: {quote(ui)};\n"
        f"  --font-text-theme: {quote(ui)};\n"
        f"  --font-monospace-theme: {quote(terminal)};\n"
        "}\n"
    )


def sync_obsidian(
    ui: str,
    terminal: str,
    enabled: bool,
    clean: bool,
) -> dict:
    vault, error = find_vault()
    if vault is None:
        return {"ok": False, "enabled": enabled, "error": error}

    snippet = vault / ".obsidian" / "snippets" / f"{OBSIDIAN_SNIPPET}.css"
    if enabled:
        try:
            atomic_write(snippet, obsidian_css(ui, terminal))
        except OSError as write_error:
            return {
                "ok": False,
                "enabled": enabled,
                "vault": str(vault),
                "error": str(write_error),
            }

        applied = set_snippet_enabled(vault, True)
        return {
            "ok": bool(applied.get("ok")),
            "enabled": True,
            "vault": str(vault),
            "snippet": str(snippet),
            "error": applied.get("error", ""),
        }

    if clean:
        try:
            snippet.unlink(missing_ok=True)
        except OSError as remove_error:
            return {
                "ok": False,
                "enabled": False,
                "vault": str(vault),
                "error": str(remove_error),
            }
        disabled = set_snippet_enabled(vault, False)
        return {
            "ok": bool(disabled.get("ok")),
            "enabled": False,
            "vault": str(vault),
            "snippet": str(snippet),
            "error": disabled.get("error", ""),
        }

    return {"ok": True, "enabled": False, "vault": str(vault)}


def run_apply(args: argparse.Namespace) -> int:
    try:
        ui = clean_family(args.ui)
        terminal = clean_family(args.terminal)
    except ValueError as error:
        return fail(str(error))

    foot = write_foot(terminal) if args.foot == "on" else {
        "ok": True,
        "skipped": True,
    }
    obsidian = sync_obsidian(
        ui,
        terminal,
        args.obsidian == "on",
        args.clean_obsidian,
    )

    result = {
        "ok": bool(foot.get("ok")),
        "ui": ui,
        "terminal": terminal,
        "foot": foot,
        "obsidian": obsidian,
    }
    print(json.dumps(result, ensure_ascii=False))
    return 0 if result["ok"] else 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    subparsers.add_parser("list", help="print the installed font families")

    apply = subparsers.add_parser("apply", help="render the selected fonts")
    apply.add_argument("--ui", required=True)
    apply.add_argument("--terminal", required=True)
    apply.add_argument("--foot", choices=("on", "off"), default="off")
    apply.add_argument("--obsidian", choices=("on", "off"), default="off")
    apply.add_argument("--clean-obsidian", action="store_true")

    args = parser.parse_args()
    if args.command == "list":
        if shutil.which("fc-list") is None:
            return fail("fc-list was not found; install fontconfig")
        print(json.dumps({"ok": True, "fonts": list_fonts()}, ensure_ascii=False))
        return 0
    return run_apply(args)


if __name__ == "__main__":
    sys.exit(main())
